import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const EN_LOCALE_DIR = join(SCRIPT_DIR, "..", "locales", "en");
const KEYS_OUTPUT_PATH = join(SCRIPT_DIR, "..", "src", "keys.ts");

type JsonObject = Record<string, unknown>;

function flattenKeys(node: JsonObject, prefix: string): string[] {
  const keys: string[] = [];
  for (const [segment, value] of Object.entries(node)) {
    const path = prefix ? `${prefix}.${segment}` : segment;
    if (typeof value === "string") {
      keys.push(path);
    } else if (value !== null && typeof value === "object" && !Array.isArray(value)) {
      keys.push(...flattenKeys(value as JsonObject, path));
    } else {
      throw new Error(`@forge/i18n: leaf value at "${path}" must be a string, got ${typeof value}`);
    }
  }
  return keys;
}

// Exported (rather than only used by main()) so the test suite can assert
// keys.ts hasn't gone stale relative to locales/en/ -- the same staleness
// check this package's "Done when" criteria require of CI.
export function collectTranslationKeys(localeDir: string = EN_LOCALE_DIR): string[] {
  const files = readdirSync(localeDir).filter((file) => file.endsWith(".json"));
  const keys: string[] = [];
  for (const file of files) {
    const namespace = file.replace(/\.json$/, "");
    const content = JSON.parse(readFileSync(join(localeDir, file), "utf-8")) as JsonObject;
    keys.push(...flattenKeys(content, namespace));
  }
  return keys.sort();
}

function renderKeysFile(keys: string[]): string {
  const union = keys.map((key) => `  | "${key}"`).join("\n");
  const array = keys.map((key) => `  "${key}",`).join("\n");
  return `// AUTO-GENERATED by scripts/generate-types.ts -- do not edit by hand.
// Regenerate with \`pnpm --filter @forge/i18n run generate-types\`
// (also runs automatically as part of \`pnpm --filter @forge/i18n build\`).
// Source of truth: locales/en/*.json.

export type TranslationKey =
${union};

export const TRANSLATION_KEYS: readonly TranslationKey[] = [
${array}
] as const;
`;
}

function main(): void {
  const keys = collectTranslationKeys();
  mkdirSync(dirname(KEYS_OUTPUT_PATH), { recursive: true });
  writeFileSync(KEYS_OUTPUT_PATH, renderKeysFile(keys), "utf-8");
  // eslint-disable-next-line no-console
  console.log(`@forge/i18n: wrote ${keys.length} translation keys to src/keys.ts`);
}

// Runs only when this file is executed directly (`tsx scripts/generate-types.ts`),
// not when the test suite imports collectTranslationKeys().
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  main();
}
